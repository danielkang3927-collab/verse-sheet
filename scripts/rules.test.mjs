// 보안 규칙 단위 테스트 — Firestore 에뮬레이터에서 실제 규칙 파일을 실행해 검증
import { initializeTestEnvironment, assertFails, assertSucceeds } from '@firebase/rules-unit-testing';
import fs from 'node:fs';
const env = await initializeTestEnvironment({ projectId: 'verse-sheet-test', firestore: { rules: fs.readFileSync(new URL('../firestore.rules', import.meta.url), 'utf8') } });
const verses = Array.from({ length: 167 }, (_, i) => ({ ref: 'r' + i }));
const state = (learned, extra = {}) => ({ verses, progress: {}, meta: Object.assign({ learned }, extra.meta || {}), updatedAt: Date.now() });
const A = env.authenticatedContext('alice', { email: 'alice@example.com' }).firestore();
const B = env.authenticatedContext('bob', { email: 'bob@example.com' }).firestore();
const ADMIN = env.authenticatedContext('admin', { email: 'danielkang3927@gmail.com' }).firestore();
const ANON = env.unauthenticatedContext().firestore();
let n = 0; const t = async (name, p) => { await p; n++; console.log('✓ ' + name); };

await t('본인: 기록 처음 저장', assertSucceeds(A.doc('users/alice/data/state').set(state(0))));
await t('본인: 기록이 늘어나는 저장', assertSucceeds(A.doc('users/alice/data/state').set(state(40))));
await t('본인: 같은 수 저장', assertSucceeds(A.doc('users/alice/data/state').set(state(40))));
await t('본인: 3개 이내 감소 허용(오차)', assertSucceeds(A.doc('users/alice/data/state').set(state(38))));
await t('본인: 기록이 크게 줄어드는 저장 거부', assertFails(A.doc('users/alice/data/state').set(state(5))));
await t('본인: meta 없는 옛 형식(=0) 저장 거부', assertFails(A.doc('users/alice/data/state').set({ verses, progress: {}, updatedAt: 1 })));
await t('본인: 구절 목록이 비는 저장 거부', assertFails(A.doc('users/alice/data/state').set({ verses: [], progress: {}, meta: { learned: 40 }, updatedAt: 1 })));
await t('본인: 기록 문서 삭제 거부', assertFails(A.doc('users/alice/data/state').delete()));
await t('본인: 명시적 초기화(10분 이내 표시)만 감소 허용', assertSucceeds(A.doc('users/alice/data/state').set(state(0, { meta: { reset: Date.now() } }))));
await t('본인: 오래된 초기화 표시는 무효', (async () => { await assertSucceeds(A.doc('users/alice/data/state').set(state(30))); await assertFails(A.doc('users/alice/data/state').set(state(0, { meta: { reset: Date.now() - 3600000 } }))); })());
await t('본인: 오답 문서 저장', assertSucceeds(A.doc('users/alice/data/errors').set({ errors: [], updatedAt: 1 })));
await t('본인: 오답 문서 삭제 거부', assertFails(A.doc('users/alice/data/errors').delete()));
await t('본인: 자기 기록 읽기', assertSucceeds(A.doc('users/alice/data/state').get()));
await t('타인: 남의 기록 읽기 거부', assertFails(B.doc('users/alice/data/state').get()));
await t('타인: 남의 기록 쓰기 거부', assertFails(B.doc('users/alice/data/state').set(state(99))));
await t('비로그인: 읽기 거부', assertFails(ANON.doc('users/alice/data/state').get()));
await t('본인: 백업 저장', assertSucceeds(A.doc('users/alice/backups/2026-11-12').set({ savedAt: Date.now(), progress: {} })));
await t('본인: 백업 목록 읽기', assertSucceeds(A.collection('users/alice/backups').orderBy('savedAt', 'desc').get()));
await t('본인: 최근 백업 삭제 거부', assertFails(A.doc('users/alice/backups/2026-11-12').delete()));
await t('본인: 30일 지난 백업 정리 허용', (async () => { await assertSucceeds(A.doc('users/alice/backups/2026-09-01').set({ savedAt: Date.now() - 40 * 86400000 })); await assertSucceeds(A.doc('users/alice/backups/2026-09-01').delete()); })());
await t('타인: 남의 백업 읽기 거부', assertFails(B.doc('users/alice/backups/2026-11-12').get()));
await t('본인: 정해지지 않은 경로 쓰기 거부', assertFails(A.doc('users/alice/other/x').set({ a: 1 })));
await t('관리자: 키 문서 쓰기', assertSucceeds(ADMIN.doc('config/tts').set({ key: 'k' })));
await t('일반 사용자: 키 문서 읽기 거부', assertFails(A.doc('config/tts').get()));
await t('일반 사용자: 키 문서 쓰기 거부', assertFails(A.doc('config/tts').set({ key: 'x' })));
await t('관리자: 공개 설정 쓰기', assertSucceeds(ADMIN.doc('config/public').set({ ready: ['v'] })));
await t('일반 사용자: 공개 설정 읽기', assertSucceeds(A.doc('config/public').get()));
await t('일반 사용자: 공개 설정 쓰기 거부', assertFails(A.doc('config/public').set({ ready: [] })));
await t('관리자: 음성 저장', assertSucceeds(ADMIN.doc('audio/k1').set({ b64: 'x' })));
await t('일반 사용자: 음성 재생(읽기)', assertSucceeds(A.doc('audio/k1').get()));
await t('일반 사용자: 음성 쓰기 거부', assertFails(A.doc('audio/k1').set({ b64: 'y' })));
await t('비로그인: 음성 읽기 거부', assertFails(ANON.doc('audio/k1').get()));
await t('함께 보기: 자기 줄 쓰기', assertSucceeds(A.doc('board/alice').set({ name: 'A' })));
await t('함께 보기: 남의 줄 쓰기 거부', assertFails(B.doc('board/alice').set({ name: 'X' })));
await t('함께 보기: 로그인한 사람 읽기', assertSucceeds(B.collection('board').get()));
await t('함께 보기: 비로그인 읽기 거부', assertFails(ANON.collection('board').get()));
await env.cleanup(); console.log(`규칙 테스트 ${n}건 통과`);
